package main

import "fmt"

func main() {

	// Integer
	var age int = 22

	// Floating-point
	var salary float64 = 45000.50

	// Boolean
	var isEmployee bool = true

	// String
	var name string = "Piyush"

	fmt.Println("Name:", name)
	fmt.Println("Age:", age)
	fmt.Println("Salary:", salary)
	fmt.Println("Is Employee:", isEmployee)
}