package main

import "fmt"

func main() {

	// Variables
	var name string = "Piyush"
	var age int = 22

	fmt.Println("Name:", name)
	fmt.Println("Age:", age)

	// Changing variable value
	age = 23

	fmt.Println("Updated Age:", age)

	// Constant
	const country string = "India"

	fmt.Println("Country:", country)
}