package main

import "fmt"

func main() {

	// variables declaration

	var i int
	var f float64
	var b bool
	var s string
	var by byte
	var r rune

	fmt.Printf("int: %v\n", i)
	fmt.Printf("float64: %v\n", f)
	fmt.Printf("bool: %v\n", b)
	fmt.Printf("string: %s\n", s)
	fmt.Printf("byte: %v\n", by)
	fmt.Printf("rune: %v\n", r)

}
